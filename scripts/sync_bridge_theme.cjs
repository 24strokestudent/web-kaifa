const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const target=path.join(root,'projects/web/ai-browser-bridge/theme.css');
const theme='/* Generated by scripts/sync_bridge_theme.cjs from root tokens.css. */\n'+fs.readFileSync(path.join(root,'tokens.css'),'utf8');
if(process.argv.includes('--check')){if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==theme)throw Error('Bridge theme differs from root tokens.css');console.log('PASS: extension and site share root design tokens.');}
else{fs.writeFileSync(target,theme);console.log('Synced bridge design tokens.');}
